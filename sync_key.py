import os
import base64

def main():
    key = os.environ.get("SECRET_GEMINI_KEY", "").strip()
    if not key:
        print("No SECRET_GEMINI_KEY provided in environment.")
        return

    encoded = base64.b64encode(key.encode("utf-8")).decode("utf-8")
    content = f'''# Auto-generated by GitHub Actions from Repository Secrets
import base64

_ENCODED_KEY = "{encoded}"

def get_embedded_gemini_key() -> str:
    if not _ENCODED_KEY:
        return ""
    try:
        return base64.b64decode(_ENCODED_KEY.encode("utf-8")).decode("utf-8")
    except Exception:
        return ""
'''
    with open("src/embedded_key.py", "w", encoding="utf-8") as f:
        f.write(content)
    print("Successfully populated src/embedded_key.py!")

if __name__ == "__main__":
    main()
